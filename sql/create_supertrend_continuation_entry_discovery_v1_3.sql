    start_cum_amount DOUBLE NULL,
    early1_amount DOUBLE NULL,
    early2_cum_amount DOUBLE NULL,
    early3_cum_amount DOUBLE NULL,
    early1_high_return_pct DOUBLE NULL,
    early2_high_return_pct DOUBLE NULL,
    early3_high_return_pct DOUBLE NULL,
    early2_to_early3_amount_growth DOUBLE NULL,
    early3_break_start_high TINYINT NOT NULL DEFAULT 0,

    st_up_max_return_pct DOUBLE NULL,
    post_early3_extension_pct DOUBLE NULL,
    estimated_max_return_after_entry_pct DOUBLE NULL,
    estimated_lost_move_before_entry_pct DOUBLE NULL,
    continuation_success TINYINT NOT NULL DEFAULT 0,
    continuation_fail TINYINT NOT NULL DEFAULT 0,
    continuation_score_v1_3 DOUBLE NOT NULL DEFAULT 0,
    continuation_label_v1_3 VARCHAR(80) NOT NULL,

    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

    UNIQUE KEY uq_st_cont_entry_v13 (source_v1_2_id, entry_type),
    KEY ix_st_cont_entry_v13_group (trade_date, code, st_period, st_multiplier, entry_type),
    KEY ix_st_cont_entry_v13_quality (entry_type, continuation_label_v1_3, quality_label),
    KEY ix_st_cont_entry_v13_score (continuation_score_v1_3, estimated_max_return_after_entry_pct),
    KEY ix_st_cont_entry_v13_filter (live_filter_label_v1_2, post_diagnostic_label_v1_2)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

